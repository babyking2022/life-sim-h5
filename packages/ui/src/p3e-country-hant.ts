type DisplayNamesCtor = new (
  locales: string | string[],
  opts: { type: string }
) => { of: (code: string) => string };

// 懶初始化單例：Intl.DisplayNames 建構成本不低，絕不在每次渲染時重複建立。
let cachedDn: { of: (code: string) => string } | null = null;
let cachedDnUnavailable = false;
const nameCache = new Map<string, string>();

/**
 * 運行時優先嘗試 Intl.DisplayNames（瀏覽器支援且回傳真名稱時）。
 * 失敗或為敏感地區時回 null，由呼叫方回退靜態表。DisplayNames 實例只建構一次（快取）。
 */
function runtimeZhHant(regionCode: string): string | null {
  try {
    if (cachedDnUnavailable) return null;
    const iso2 = ISO2_BY_ISO3[regionCode];
    if (iso2 === undefined) return null;
    if (cachedDn === null) {
      const g = globalThis as { Intl?: { DisplayNames?: DisplayNamesCtor } };
      const Ctor = g.Intl?.DisplayNames;
      if (typeof Ctor !== "function") {
        cachedDnUnavailable = true;
        return null;
      }
      const dn = new Ctor(["zh-Hant"], { type: "region" });
      if (typeof dn.of !== "function") {
        cachedDnUnavailable = true;
        return null;
      }
      cachedDn = dn;
    }
    const name = cachedDn.of(iso2);
    if (typeof name !== "string" || name.length === 0) return null;
    if (name.toUpperCase() === iso2.toUpperCase()) return null; // 回傳原代碼，非真名稱
    return name;
  } catch {
    cachedDnUnavailable = true;
    cachedDn = null;
    return null;
  }
}

/** 以 region code（ISO3）取得真正 zh-Hant 國名；查無則回空字串，由呼叫方顯示「未知地區」。結果快取。 */
export function zhHantCountryName(regionCode: string): string {
  if (regionCode.length === 0) return "";
  const cached = nameCache.get(regionCode);
  if (cached !== undefined) return cached;
  const live = runtimeZhHant(regionCode);
  const result = live !== null ? live : (ZH_HANT_BY_ISO3[regionCode] ?? "");
  nameCache.set(regionCode, result);
  return result;
}
